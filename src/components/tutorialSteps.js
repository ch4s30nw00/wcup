// "드리블 다음에 바로 슛"으로 가르치면 정작 그 경기에서 할 일과 어긋난다.
//
// focus는 그 단계가 가리키는 대상이다. 화면 크기와 배치가 사람마다 달라서
// "왼쪽 위 버튼"식 설명이 통하지 않는다 — 실제 그 오브젝트를 점멸시킨다.
//   board  : 'ball' | 'carrier' | { id } — 보드 위에서 깜빡일 대상
//   action : 공 소유자 액션 메뉴에서 깜빡일 항목
//   ui     : 보드 밖 버튼 ('confirm' = 전술 확정)

